#!/usr/bin/env python3
"""One place to compare the team's methods: complete ranking, thresholded, bootstrap.

Reads what ``scripts/evaluate.py`` and ``scripts/compare_methods.py`` wrote under
``artifacts/`` and writes ``artifacts/reports/summary.md`` (+ ``summary.json``) with:

1. complete-ranking metrics and latency per method (the primary benchmark result),
2. thresholded metrics per method, with the threshold value and which method selected it,
3. paired-bootstrap differences against the baseline (when the compare files exist),
4. method details required by the shared guide (checkpoint, manifest, parameters, hardware).

Methods are grouped by family into the three team methods: Baseline (exact cosine),
MINER (five-crop fusion) and FAISS (search block). Missing files are reported, not fatal.

Usage::

    python scripts/summarize_results.py                       # every registered method with a report
    python scripts/summarize_results.py --methods global five_crop faiss_ivf --baseline global
"""

import argparse
from datetime import date
import json
from pathlib import Path
import sys

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from vision_retrieval.config import load_config
from vision_retrieval.methods import get_method, list_methods

TEAM_METHOD = {"exact": "Baseline", "five_crop": "MINER", "faiss": "FAISS"}
METRICS = ("recall_at_1", "recall_at_5", "recall_at_10", "mrr", "ndcg_at_10")


def _load(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def _fmt(value, digits=4):
    return "–" if value is None else f"{value:.{digits}f}"


def _signed(entry, key):
    if entry is None:
        return "–"
    value = entry[key]
    text = f"{value['difference']:+.4f}"
    return text if value["significant"] else text + " (n.s.)"


def collect(config, methods, baseline):
    reports_dir = config.output_root / "reports"
    predictions_dir = config.output_root / "predictions"
    rows = []
    for name in methods:
        spec = get_method(name)
        metrics = _load(reports_dir / f"{name}_metrics.json")
        metadata = _load(predictions_dir / f"{name}.metadata.json")
        compare = None if name == baseline else _load(reports_dir / f"compare_{baseline}_vs_{name}.json")
        threshold_file = None
        if metadata and metadata["parameters"].get("threshold_file"):
            threshold_file = _load(Path(metadata["parameters"]["threshold_file"]))
        rows.append(
            {
                "method": name,
                "team_method": TEAM_METHOD.get(spec.family, spec.family),
                "label": spec.label,
                "threshold_source": spec.threshold_method,
                "metrics": metrics,
                "metadata": metadata,
                "compare": compare,
                "threshold_file": threshold_file,
            }
        )
    return rows


def render(rows, baseline, target_recall) -> str:
    lines = [
        "# Method comparison summary",
        "",
        f"Generated by `scripts/summarize_results.py` from `artifacts/` on {date.today().isoformat()}. "
        "Same frozen SigLIP 2 checkpoint, same Flickr8k test manifest, same evaluator for every row. "
        f"Baseline for differences: `{baseline}`. Regenerate the tracked copy with "
        "`python scripts/summarize_results.py --output docs/RESULTS.md`.",
        "",
        "## 1. Complete ranking (primary benchmark result)",
        "",
        "| Team method | Method | R@1 | R@5 | R@10 | MRR | nDCG@10 | Search mean (ms) | E2E mean (ms) | E2E p50 (ms) | E2E p95 (ms) |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        m = row["metrics"]
        if m is None:
            lines.append(f"| {row['team_method']} | `{row['method']}` | not evaluated yet |  |  |  |  |  |  |  |  |")
            continue
        lines.append(
            f"| {row['team_method']} | `{row['method']}` | "
            + " | ".join(_fmt(m[k]) for k in METRICS)
            + f" | {m['search']['mean_ms']:.2f} | {m['end_to_end']['mean_ms']:.2f} | "
            f"{m['end_to_end']['p50_ms']:.2f} | {m['end_to_end']['p95_ms']:.2f} |"
        )

    lines += [
        "",
        f"## 2. Validation-selected score threshold (target: keep {target_recall:.0%} of relevant images on validation)",
        "",
        "Reported separately from the complete ranking, as the shared guide requires. "
        "`Threshold from` names the method whose validation scores selected the cutoff; "
        "FAISS methods reuse the baseline's because they score on the same cosine scale. "
        "Do not compare the cutoff values across score scales; compare the columns at the matched operating point.",
        "",
        "| Team method | Method | Threshold | Threshold from | Relevant retained (recall) | Precision | F1 | Avg results/query | Queries with ≥1 result | Thr. R@1 | Thr. R@5 | Thr. R@10 | Thr. MRR | Thr. nDCG@10 |",
        "|---|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        m = row["metrics"]
        t = (m or {}).get("thresholded")
        if t is None:
            lines.append(
                f"| {row['team_method']} | `{row['method']}` | not run | `{row['threshold_source']}` |  |  |  |  |  |  |  |  |  |  |"
            )
            continue
        lines.append(
            f"| {row['team_method']} | `{row['method']}` | {t['threshold']:.4f} | `{row['threshold_source']}` | "
            f"{t['candidate_recall']:.4f} | {t['candidate_precision']:.4f} | {t['candidate_f1']:.4f} | "
            f"{t['average_results_per_query']:.2f} | {t['query_coverage']:.4f} | "
            + " | ".join(_fmt(t[k]) for k in METRICS)
            + " |"
        )

    lines += [
        "",
        f"## 3. Paired image-clustered bootstrap vs `{baseline}` (95% CI, 10,000 resamples)",
        "",
        "| Team method | Method | ΔR@1 [95% CI] | ΔR@5 | ΔR@10 | ΔMRR | ΔnDCG@10 | Verdict |",
        "|---|---|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        if row["method"] == baseline:
            continue
        c = row["compare"]
        if c is None:
            lines.append(f"| {row['team_method']} | `{row['method']}` | not run (scripts/compare_methods.py) |  |  |  |  |  |")
            continue
        r1 = c["recall_at_1"]
        if not r1["significant"]:
            verdict = "no significant R@1 difference"
        elif r1["difference"] > 0:
            verdict = "R@1 gain supported"
        else:
            verdict = "significantly lower R@1"
        if all(abs(c[k]["difference"]) < 1e-12 for k in METRICS):
            verdict = "identical ranking"
        lines.append(
            f"| {row['team_method']} | `{row['method']}` | {r1['difference']:+.4f} [{r1['ci95_low']:+.4f}, {r1['ci95_high']:+.4f}] | "
            + " | ".join(_signed(c, k) for k in METRICS[1:])
            + f" | {verdict} |"
        )

    lines += [
        "",
        "## 4. Method details (shared guide, step 7)",
        "",
        "| Method | Checkpoint revision | Test manifest | Parameters | Build (s) | Device | Timing protocol | Threshold file |",
        "|---|---|---|---|---:|---|---|---|",
    ]
    for row in rows:
        md = row["metadata"]
        if md is None:
            lines.append(f"| `{row['method']}` | not evaluated yet |  |  |  |  |  |  |")
            continue
        p = md["parameters"]
        skip = {
            "split", "method_family", "method_label", "method_build_seconds", "alpha", "score_threshold",
            "threshold_source_method", "threshold_file", "threshold_selection_metric", "threshold_target_recall",
            "crop_ratio", "timing_runs", "warmup_queries", "batch_size", "index_build_seconds", "index_bytes",
            "gallery_size", "vector_dimension", "faiss_threads", "seed", "index_parameters",
        }
        shown = {k: v for k, v in p.items() if k not in skip}
        if row["method"] == "five_crop":
            shown = {"alpha": p.get("alpha"), "crop_ratio": p.get("crop_ratio")}
        params = ", ".join(f"{k}={v}" for k, v in shown.items()) or "–"
        lines.append(
            f"| `{row['method']}` | `{md['checkpoint_revision'][:8]}…` | `{md['manifest_sha256'][:8]}…` | {params} | "
            f"{p.get('method_build_seconds', 0.0):.3f} | {md['hardware']['device']} | "
            f"batch {p.get('batch_size')}, warm-up {p.get('warmup_queries')}, {p.get('timing_runs')} runs | "
            + (f"`{Path(p['threshold_file']).name}`" if p.get("threshold_file") else "–")
            + " |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, default=PROJECT_ROOT / "configs" / "experiment.yaml")
    parser.add_argument("--methods", nargs="+", default=None, help="default: every registered method")
    parser.add_argument("--baseline", default="global")
    parser.add_argument("--output", type=Path, default=None, help="default: artifacts/reports/summary.md")
    args = parser.parse_args()

    config = load_config(args.config)
    methods = args.methods or list(list_methods())
    for name in methods + [args.baseline]:
        get_method(name)  # fail early on a typo
    rows = collect(config, methods, args.baseline)
    markdown = render(rows, args.baseline, config.threshold_target_recall)
    output = args.output or (config.output_root / "reports" / "summary.md")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(markdown, encoding="utf-8")
    output.with_suffix(".json").write_text(
        json.dumps(
            [{k: v for k, v in row.items() if k != "metadata"} for row in rows],
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    print(markdown)
    print(f"wrote {output} and {output.with_suffix('.json')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
